-- HU8: solo se puede crear una cuenta si el dueño del correo la autoriza desde el enlace que le llega.
-- Antes de autorizar solo se guarda el email: nada de nombre ni contraseña.
--   * token_hash: SHA-256 del token del enlace (el token en claro solo viaja en el correo).
--   * fecha_expiracion: hasta cuándo sirve el enlace (en hora UTC).
--   * fecha_ultimo_envio: para no reenviar más de un correo por minuto al mismo email.
--   * bloqueado_hasta: si el dueño respondió "No fui yo", no se aceptan solicitudes hasta esa hora.
create table solicitud_registro (
    codigo_solicitud   integer generated by default as identity primary key,
    email              varchar(255) not null unique,
    token_hash         varchar(64)  unique,
    fecha_expiracion   timestamp    not null,
    fecha_ultimo_envio timestamp    not null,
    bloqueado_hasta    timestamp
);

-- Igual que las demás tablas de soporte: la API pública de Supabase no la lee directamente.
alter table solicitud_registro enable row level security;
