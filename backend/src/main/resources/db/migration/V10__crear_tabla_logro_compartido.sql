-- HU21: enlace público para compartir un logro (meta cumplida).
-- Un enlace por usuario y meta: si se comparte otra vez, se reutiliza el mismo token.
-- El token es aleatorio para no exponer los códigos internos de la meta ni del usuario.
create table logro_compartido (
    codigo_logro   integer generated by default as identity primary key,
    token          varchar(16) not null unique,
    codigo_meta    integer     not null references meta(codigo_meta) on delete cascade,
    codigo_usuario integer     not null references usuario(codigo_usuario) on delete cascade,
    fecha_creacion date        not null default current_date,
    constraint uq_logro_meta_usuario unique (codigo_meta, codigo_usuario)
);

-- Igual que las demás tablas de soporte: la API pública de Supabase no la lee directamente.
alter table logro_compartido enable row level security;
