-- HU11: catálogo de insignias y las que gana cada usuario.
-- criterio dice qué se cuenta: METAS_CUMPLIDAS (todas), METAS_CUMPLIDAS_PLAZO (solo las del
-- plazo_requerido) o TIPOS_DISTINTOS (cuántos tipos de meta distintos ha cumplido).
create table insignia (
    codigo_insignia    integer generated by default as identity primary key,
    nombre             varchar(60)  not null unique,
    descripcion        varchar(150) not null,
    icono              varchar(30)  not null,
    criterio           varchar(25)  not null
                       check (criterio in ('METAS_CUMPLIDAS', 'METAS_CUMPLIDAS_PLAZO', 'TIPOS_DISTINTOS')),
    plazo_requerido    varchar(10)  check (plazo_requerido in ('CORTO', 'MEDIANO', 'LARGO')),
    cantidad_requerida integer      not null check (cantidad_requerida > 0),
    constraint ck_insignia_plazo check ((criterio = 'METAS_CUMPLIDAS_PLAZO') = (plazo_requerido is not null))
);

-- Clase de asociación Usuario–Insignia: cada insignia se gana una sola vez (llave compuesta).
create table usuario_insignia (
    codigo_usuario  integer not null references usuario(codigo_usuario) on delete cascade,
    codigo_insignia integer not null references insignia(codigo_insignia) on delete cascade,
    fecha_obtenida  date    not null default current_date,
    primary key (codigo_usuario, codigo_insignia)
);

