-- LOG DE ACTIVIDAD (auditoría)
-- Una fila por cada acción que un usuario intenta (crear, editar, consultar...),
-- con su resultado. Sirve para rastrear quién hizo qué y cuándo, y detectar fraude.
--
-- Diseño pensado para crecer: agregar una HU nueva NO requiere migrar esta tabla.
--   * accion y entidad son texto: los valores válidos los controlan los enums de Java
--     (AccionLog, EntidadLog), no un CHECK de la base.
--   * codigo_usuario y codigo_entidad no tienen llave foránea: el log es un histórico
--     que debe sobrevivir al borrado de la meta/usuario y también registrar intentos
--     con códigos que no existen (típico de un intento de fraude).
create table log_actividad (
    codigo_log      integer generated by default as identity primary key,
    fecha_hora      timestamptz  not null default now(),
    codigo_usuario  integer,                       -- quién (null si no se sabe)
    accion          varchar(30)  not null,         -- qué: CREAR_META, EDITAR_META, LISTAR_METAS...
    entidad         varchar(30)  not null,         -- sobre qué tipo de dato: META, USUARIO...
    codigo_entidad  integer,                       -- sobre cuál (null si es una consulta general)
    resultado       varchar(10)  not null
                    check (resultado in ('EXITO','ERROR')),
    detalle         text                           -- JSON corto con datos de la acción o del error
);

create index idx_log_usuario_fecha on log_actividad (codigo_usuario, fecha_hora desc);
create index idx_log_entidad       on log_actividad (entidad, codigo_entidad);
create index idx_log_fecha         on log_actividad (fecha_hora desc);

-- Solo escritura: un log que se puede editar o borrar no sirve para auditar.
create function log_actividad_inmutable() returns trigger
language plpgsql
set search_path = ''
as $$
begin
    raise exception 'log_actividad es de solo escritura: no se permite %', tg_op;
end;
$$;

create trigger trg_log_actividad_no_modificar
    before update or delete on log_actividad
    for each row execute function log_actividad_inmutable();

create trigger trg_log_actividad_no_vaciar
    before truncate on log_actividad
    for each statement execute function log_actividad_inmutable();

-- Que la API pública de Supabase (anon/authenticated) no pueda leer ni escribir los logs.
-- El backend se conecta como dueño de la tabla, por eso no se ve afectado.
alter table log_actividad enable row level security;
