-- Sub-metas diarias: la meta es el destino (cumplida o no) y las sub-metas son el camino.
-- Cada sub-meta es Sí/No o medible; cada participante registra su día en registro_sub_meta.
-- La tabla registro de la HU5 (retirada) se elimina: la reemplaza registro_sub_meta.
drop table if exists registro;

create table sub_meta (
    codigo_sub_meta integer generated by default as identity primary key,
    codigo_meta     integer       not null references meta(codigo_meta) on delete cascade,
    nombre          varchar(100)  not null,
    pregunta        varchar(200),
    tipo            varchar(10)   not null check (tipo in ('SI_NO', 'MEDIBLE')),
    unidad          varchar(30),
    objetivo        numeric(12,2),
    tipo_objetivo   varchar(12)   check (tipo_objetivo in ('AL_MENOS', 'COMO_MAXIMO')),
    -- días en que toca, un bit por día: lunes = 1, martes = 2, ... domingo = 64 (127 = todos)
    dias            smallint      not null default 127 check (dias between 1 and 127),
    notas           varchar(500),
    fecha_creacion  date          not null default current_date,
    constraint ck_sub_meta_tipo check (
        (tipo = 'SI_NO' and unidad is null and objetivo is null and tipo_objetivo is null)
        or (tipo = 'MEDIBLE' and unidad is not null and objetivo > 0 and tipo_objetivo is not null))
);
create index idx_sub_meta_meta on sub_meta (codigo_meta);

-- valor: en Sí/No 1 = hecho y 0 = no hecho; en medible, la cantidad del día
create table registro_sub_meta (
    codigo_registro integer generated by default as identity primary key,
    codigo_sub_meta integer       not null references sub_meta(codigo_sub_meta) on delete cascade,
    codigo_usuario  integer       not null references usuario(codigo_usuario) on delete cascade,
    fecha           date          not null,
    valor           numeric(12,2) not null check (valor >= 0),
    constraint uq_registro_sub_meta_dia unique (codigo_sub_meta, codigo_usuario, fecha)
);

alter table sub_meta enable row level security;
alter table registro_sub_meta enable row level security;
